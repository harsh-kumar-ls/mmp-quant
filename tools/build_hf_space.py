"""Assemble the Hugging Face Space folder (build/hf-space/) for deployment.

    .venv/bin/python tools/build_hf_space.py          # then upload build/hf-space

Contents: the package source, config.yaml merged with
deploy/hf-space/overrides.yaml (RapidOCR off the Mac), the built React UI
(webapp-react/dist -- run `npm run build` first), the presentation styles, and
each scored corpus video's result.json + report.md (no frames, audio or video
files). Never copied: videos, rating packages, ratings, PROGRESS.md and the private project instructions.

User's decision, 12 Nov 2026: a public Space, given to the professor only after
her ratings are returned.
"""

from __future__ import annotations

import shutil
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "build" / "hf-space"
DEPLOY = ROOT / "deploy" / "hf-space"


def _merge(base: dict, over: dict) -> dict:
    for k, v in over.items():
        if isinstance(v, dict) and isinstance(base.get(k), dict):
            _merge(base[k], v)
        else:
            base[k] = v
    return base


def main() -> None:
    dist = ROOT / "webapp-react" / "dist"
    if not (dist / "index.html").exists():
        raise SystemExit("webapp-react/dist missing: run `npm run build` in webapp-react/")
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)

    for name in ("Dockerfile", "README.md", "warmup.py"):
        shutil.copy(DEPLOY / name, OUT / name)
    shutil.copy(ROOT / "pyproject.toml", OUT / "pyproject.toml")
    shutil.copytree(ROOT / "src", OUT / "src",
                    ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
    shutil.copytree(dist, OUT / "webapp-react" / "dist")

    cfg = _merge(yaml.safe_load((ROOT / "config.yaml").read_text()),
                 yaml.safe_load((DEPLOY / "overrides.yaml").read_text()))
    (OUT / "config.yaml").write_text(
        "# Generated by tools/build_hf_space.py: config.yaml + deploy/hf-space/overrides.yaml\n"
        + yaml.safe_dump(cfg, sort_keys=False))

    (OUT / "data" / "videos").mkdir(parents=True)
    (OUT / "data" / "videos" / ".gitkeep").touch()
    shutil.copy(ROOT / "data" / "video_styles.csv", OUT / "data" / "video_styles.csv")

    n = 0
    for result in sorted((ROOT / "runs").glob("*/result.json")):
        target = OUT / "runs" / result.parent.name
        target.mkdir(parents=True)
        shutil.copy(result, target / "result.json")
        if (result.parent / "report.md").exists():
            shutil.copy(result.parent / "report.md", target / "report.md")
        n += 1

    size = sum(f.stat().st_size for f in OUT.rglob("*") if f.is_file()) / 1e6
    print(f"{OUT}: {n} corpus reports, {size:.1f} MB")


if __name__ == "__main__":
    main()
